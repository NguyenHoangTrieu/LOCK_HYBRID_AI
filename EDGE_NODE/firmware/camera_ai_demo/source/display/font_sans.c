const font_clock_glyph_t *FONT_GetClockGlyph(char c)
{
    if (c >= '0' && c <= '9')
    {
        return &FONT_CLOCK_TABLE[c - '0'];
    }
    if (c == ':')
    {
        return &FONT_CLOCK_TABLE[10];
    }
    if (c == '-')
    {
        return &FONT_CLOCK_TABLE[11];
    }
    return &FONT_CLOCK_TABLE[12]; /* space */
}

const font_text_glyph_t *FONT_GetTextGlyph(char c)
{
    if ((uint8_t)c >= 32U && (uint8_t)c <= 126U)
    {
        return &FONT_TEXT_TABLE[(uint8_t)c - 32U];
    }
    return &FONT_TEXT_TABLE[0]; /* space fallback */
}

uint16_t FONT_GetClockStringWidth(const char *str)
{
    uint16_t w = 0U;
    while (*str)
    {
        w = (uint16_t)(w + FONT_GetClockGlyph(*str++)->adv);
    }
    return w;
}

uint16_t FONT_GetTextStringWidth(const char *str)
{
    uint16_t w = 0U;
    while (*str)
    {
        w = (uint16_t)(w + FONT_GetTextGlyph(*str++)->adv);
    }
    return w;
}
